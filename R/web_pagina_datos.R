# Escribe docs/datos_diccionario.md y docs/data_dictionary.md (UTF-8 y LF) y devuelve sus rutas.
exportar_diccionario_datos <- function(indicadores, vocabulario, fuentes, dir = "docs") {
  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  rutas <- file.path(dir, FICHEROS_DICCIONARIO_DATOS)
  names(rutas) <- names(FICHEROS_DICCIONARIO_DATOS)
  for (idioma in names(rutas)) {
    escribir_texto_lf(diccionario_datos_md(indicadores, vocabulario, fuentes, idioma), rutas[[idioma]])
  }
  unname(rutas)
}

# Lineas de Markdown del diccionario en un idioma ("es" o "en").
diccionario_datos_md <- function(indicadores, vocabulario, fuentes, idioma = "es") {
  tx <- TEXTOS_DICCIONARIO_DATOS[[idioma]]
  if (is.null(tx)) stop("Idioma sin textos: ", idioma, call. = FALSE)
  c(tx$aviso, "",
    valores_columnas_md(indicadores, vocabulario, fuentes, idioma, tx),
    indicadores_md(indicadores, vocabulario, idioma, tx))
}

# Texto de Markdown sin marcas: escapa los signos que el Markdown interpretaria.
escapar_md <- function(x) gsub("([\\\\`*_\\[\\]<>|#~])", "\\\\\\1", x, perl = TRUE)

codigo_md <- function(x) paste0("`", x, "`")

fila_md <- function(...) paste0("| ", paste(..., sep = " | "), " |")

tabla_md <- function(cabecera, filas) {
  c(fila_md(paste(cabecera, collapse = " | ")), fila_md(paste(rep("---", length(cabecera)), collapse = " | ")), filas, "")
}

# Etiquetas de un grupo del vocabulario, con la clave como nombre y en su orden.
vocabulario_de <- function(vocabulario, grupo, idioma) {
  v <- vocabulario[vocabulario$grupo == grupo, ]
  stats::setNames(as.character(v[[idioma]]), v$clave)
}

valores_columnas_md <- function(indicadores, vocabulario, fuentes, idioma, tx) {
  estado <- vocabulario_de(vocabulario, "estado", idioma)
  nivel <- vocabulario_de(vocabulario, "nivel", idioma)
  corte <- vocabulario_de(vocabulario, "corte", idioma)
  digitos <- ifelse(names(nivel) %in% names(NIVELES), as.character(NIVELES[names(nivel)]), "")
  digitos[names(nivel) == "nacional"] <- paste0(digitos[names(nivel) == "nacional"], " (", codigo_md("00"), ")")

  grupos <- unlist(lapply(setdiff(names(corte), "total"), function(k) {
    g <- vocabulario_de(vocabulario, k, idioma)
    if (length(g)) fila_md(codigo_md(k), codigo_md(names(g)), escapar_md(g)) else character()
  }))
  grupos <- c(fila_md(codigo_md("total"), codigo_md("total"), tx$sin_desglose), grupos)

  citadas <- unique(c(trimws(unlist(strsplit(stats::na.omit(indicadores$fuentes), ";", fixed = TRUE))), "calculo_propio"))
  f <- fuentes[fuentes$id %in% citadas, ]
  nombre <- escapar_md(if (idioma == "es") f$nombre else f$nombre_en)

  c(paste("##", tx$valores), "", tx$valores_intro, "",
    paste("###", codigo_md("estado")), "",
    tabla_md(c(tx$codigo, tx$significado), fila_md(codigo_md(names(estado)), escapar_md(estado))),
    paste("###", codigo_md("nivel")), "",
    tabla_md(c(tx$codigo, tx$significado, tx$digitos), fila_md(codigo_md(names(nivel)), escapar_md(nivel), digitos)),
    paste("###", codigo_md("corte")), "", tx$corte_intro, "",
    tabla_md(c(tx$codigo, tx$significado), fila_md(codigo_md(names(corte)), escapar_md(corte))),
    paste("###", codigo_md("grupo")), "", tx$grupo_intro, "",
    tabla_md(c(codigo_md("corte"), tx$codigo, tx$significado), grupos),
    paste("###", codigo_md("fuente")), "", tx$fuente_intro, "",
    tabla_md(c(tx$codigo, tx$fuente), fila_md(codigo_md(f$id), nombre)))
}

indicadores_md <- function(indicadores, vocabulario, idioma, tx) {
  texto <- function(base) as.character(indicadores[[paste0(base, "_", idioma)]])
  nombre <- texto("nombre")
  unidad <- texto("unidad")
  fase <- as.character(indicadores$fase)
  sin_version <- unique(fase[!fase %in% names(VERSION_DE_FASE)])
  if (length(sin_version)) {
    stop("Fase sin versi\u00f3n del atlas en VERSION_DE_FASE: ", paste(sin_version, collapse = ", "), call. = FALSE)
  }
  version <- unname(VERSION_DE_FASE[fase])
  auxiliar <- !is.na(indicadores$auxiliar_de) & nzchar(indicadores$auxiliar_de)
  numero <- ifelse(auxiliar | is.na(indicadores$id), tx$auxiliar, as.character(as.integer(indicadores$id)))
  enlace <- paste0("[", codigo_md(indicadores$codigo), "](#", indicadores$codigo, ")")
  familias <- vocabulario_de(vocabulario, "familia", idioma)
  familia <- unname(familias[sub("^([A-Z]+).*$", "\\1", indicadores$familia)])
  # Tarea 34: los indicadores de alquiler llevan, tras su familia, la de alquiler (quedarse o entrar)
  if ("familia_alquiler" %in% names(indicadores)) {
    de_alquiler <- vocabulario_de(vocabulario, "familia_alquiler", idioma)[indicadores$familia_alquiler]
    con_alquiler <- !is.na(de_alquiler)
    familia[con_alquiler] <- paste0(familia[con_alquiler], " · ", de_alquiler[con_alquiler])
  }

  intro <- sub("{m}", sum(auxiliar), sub("{n}", sum(!auxiliar), tx$diccionario_intro, fixed = TRUE), fixed = TRUE)
  resumen <- tabla_md(c(tx$numero, tx$codigo, tx$nombre, tx$unidad, tx$version),
                      fila_md(numero, enlace, escapar_md(nombre), escapar_md(unidad), version))

  vineta <- function(etiqueta, valor) if (is.na(valor) || !nzchar(valor)) character() else paste0("- **", etiqueta, ":** ", valor)
  fichas <- unlist(lapply(seq_len(nrow(indicadores)), function(k) {
    fuentes_k <- trimws(strsplit(indicadores$fuentes[k] %||% "", ";", fixed = TRUE)[[1]])
    de <- if (auxiliar[k]) trimws(strsplit(indicadores$auxiliar_de[k], ";", fixed = TRUE)[[1]]) else character()
    c(paste("###", codigo_md(indicadores$codigo[k])), "",
      paste0("**", numero[k], " \u00b7 ", escapar_md(nombre[k]), "**"), "",
      vineta(tx$unidad, escapar_md(unidad[k])),
      vineta(tx$familia, escapar_md(familia[k])),
      vineta(tx$fuentes, paste(codigo_md(fuentes_k[nzchar(fuentes_k)]), collapse = ", ")),
      vineta(tx$version, version[k]),
      if (length(de)) vineta(tx$auxiliar_de, paste0("[", codigo_md(de), "](#", de, ")", collapse = ", ")),
      vineta(tx$definicion, escapar_md(texto("definicion")[k])),
      vineta(tx$calculo, escapar_md(texto("calculo")[k])),
      vineta(tx$lectura, escapar_md(texto("lectura")[k])),
      "")
  }))

  c(paste("##", tx$diccionario), "", intro, "", resumen, fichas)
}
